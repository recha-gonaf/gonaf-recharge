#!/usr/bin/env node
/*
 * Reads the website's FR/HT legal Markdown files (source of truth stays
 * in legal/<folder>/{fr,ht}.md, exactly where it already is) and bundles
 * them into a single generated JS file that index.html loads locally.
 *
 * This runs at BUILD TIME (in CI, before the site is published) — never
 * in the browser. No GitHub API call, no token, no runtime fetch to the
 * repo. Works with a private repo because the checkout in CI already has
 * the files on disk; nothing needs network access to read them.
 *
 * Only fr/ht are bundled, matching the website's FR/HT-only language
 * selector. en.md and es.md are intentionally left untouched in the repo
 * for any direct/legal-language access outside this app.
 *
 * Usage:
 *   node build-legal-content.js
 * Run this from the repository root (or adjust ROOT below), BEFORE the
 * Pages deploy step, so legal-content.generated.js exists alongside
 * index.html when the site is published. Place it wherever your repo
 * keeps build scripts (e.g. scripts/build-legal-content.js) — the path
 * doesn't matter, only that it runs before deploy.
 */
const fs = require("fs");
const path = require("path");

// Adjust if this script lives somewhere other than the repo root.
const ROOT = __dirname;
const LEGAL_DIR = path.join(ROOT, "legal");
const OUTPUT_FILE = path.join(ROOT, "legal-content.generated.js");

// Must match the LEGAL_DOCS folder names used in index.html.
const DOCS = {
  "privacy-policy": ["fr", "ht"],
  "terms": ["fr", "ht"],
  "refunds": ["fr", "ht"]
};

const content = {};
let missing = [];

for (const [folder, langs] of Object.entries(DOCS)) {
  content[folder] = {};
  for (const lang of langs) {
    const filePath = path.join(LEGAL_DIR, folder, `${lang}.md`);
    if (!fs.existsSync(filePath)) {
      missing.push(filePath);
      continue;
    }
    content[folder][lang] = fs.readFileSync(filePath, "utf8");
  }
}

if (missing.length) {
  console.error("build-legal-content: missing files:\n" + missing.map(f => "  - " + f).join("\n"));
  process.exit(1);
}

const banner =
  "// AUTO-GENERATED by build-legal-content.js — do not edit by hand.\n" +
  "// Source of truth is legal/<folder>/{fr,ht}.md. Regenerated on every build.\n";

fs.writeFileSync(OUTPUT_FILE, banner + "window.LEGAL_CONTENT = " + JSON.stringify(content) + ";\n");
console.log("Wrote " + OUTPUT_FILE);
